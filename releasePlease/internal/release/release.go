// Package release implements the two release-please workflows for a single
// package: keeping a release PR up to date, and tagging a GitHub release
// once that PR is merged.
package release

import (
	"context"
	"fmt"
	"io"
	"net/url"
	"regexp"
	"sort"
	"strings"
	"time"

	"releasePlease/internal/changelog"
	"releasePlease/internal/commits"
	"releasePlease/internal/github"
	"releasePlease/internal/semver"
	"releasePlease/internal/updater"
)

const (
	LabelPending = "autorelease: pending"
	LabelTagged  = "autorelease: tagged"

	bodyHeader = ":robot: I have created a release *beep* *boop*\n---\n\n\n"
	bodyFooter = "\n\n---\nThis PR was generated by release-please-go, a Go port of [Release Please](https://github.com/googleapis/release-please)."
)

// Release types decide which files are updated with the new version.
const (
	TypeSimple = "simple"      // version.txt (or --version-file)
	TypeGo     = "go"          // no version file; Go versions are git tags
	TypeGradle = "java-gradle" // gradle.properties, build.gradle, build.gradle.kts
)

var ReleaseTypes = []string{TypeSimple, TypeGo, TypeGradle}

var gradleFiles = []string{"gradle.properties", "build.gradle", "build.gradle.kts"}

type Config struct {
	ReleaseType    string
	Branch         string // target branch, e.g. main
	TagPrefix      string // usually "v"
	InitialVersion string // used when there is no previous release

	// Pre-1.0 behaviour, matching release-please's options of the same name.
	BumpMinorPreMajor         bool
	BumpPatchForMinorPreMajor bool

	ChangelogPath string   // e.g. CHANGELOG.md; "" disables
	VersionFile   string   // plain-text file holding only the version; "" disables
	ExtraFiles    []string // files with x-release-please-version annotations

	Sections []changelog.Section
	WebURL   string // e.g. https://github.com, for changelog links
	DryRun   bool
}

type Runner struct {
	GH  *github.Client
	Cfg Config
	Log io.Writer
	Now func() time.Time
}

type PRResult struct {
	Version string
	PR      github.PullRequest
}

type Created struct {
	Version string
	Tag     string
	URL     string
	PR      int
}

func (r *Runner) logf(format string, args ...any) {
	if r.Log != nil {
		fmt.Fprintf(r.Log, format+"\n", args...)
	}
}

func (r *Runner) releaseBranch() string { return "release-please--branches--" + r.Cfg.Branch }

// ReleasePR opens or updates the release PR. It returns nil when there is
// nothing to release.
func (r *Runner) ReleasePR(ctx context.Context) (*PRResult, error) {
	pending, err := r.mergedPendingPRs(ctx)
	if err != nil {
		return nil, err
	}
	if len(pending) > 0 {
		r.logf("release PR #%d is merged but not yet tagged; run github-release first", pending[0].Number)
		return nil, nil
	}

	prev, prevTag, err := r.latestRelease(ctx)
	if err != nil {
		return nil, err
	}
	var raw []github.Commit
	if prev != nil {
		r.logf("latest release: %s", prevTag)
		raw, err = r.GH.CommitsBetween(ctx, prevTag, r.Cfg.Branch)
	} else {
		r.logf("no previous release found; using full history")
		raw, err = r.GH.ListCommits(ctx, r.Cfg.Branch, 10)
	}
	if err != nil {
		return nil, err
	}
	cs := make([]commits.Commit, len(raw))
	for i, c := range raw {
		cs[i] = commits.Parse(c.SHA, c.Commit.Message)
	}
	if !changelog.Releasable(r.sections(), cs) {
		r.logf("no user-facing commits since %s; nothing to release", orNone(prevTag))
		return nil, nil
	}

	next, err := NextVersion(prev, cs, r.Cfg)
	if err != nil {
		return nil, err
	}
	version := next.String()
	tag := r.Cfg.TagPrefix + version
	notes := changelog.Build(changelog.Options{
		Version:     version,
		CurrentTag:  tag,
		PreviousTag: prevTag,
		Date:        r.now(),
		RepoURL:     r.repoURL(),
		Sections:    r.sections(),
	}, cs)

	files, err := r.updatedFiles(ctx, version, notes)
	if err != nil {
		return nil, err
	}

	title := fmt.Sprintf("chore(%s): release %s", r.Cfg.Branch, version)
	body := bodyHeader + strings.TrimRight(notes, "\n") + bodyFooter
	if warning, err := r.goModuleWarning(ctx, next); err != nil {
		return nil, err
	} else if warning != "" {
		r.logf("warning: %s", warning)
		// Keep it after the notes' closing "---" so it never ends up in the release.
		body = strings.Replace(body, bodyFooter, "\n\n---\n> [!WARNING]\n> "+warning+"\n"+strings.TrimPrefix(bodyFooter, "\n\n---"), 1)
	}
	if r.Cfg.DryRun {
		r.logf("[dry run] would open %q from %s with files %v\n\n%s", title, r.releaseBranch(), sortedKeys(files), notes)
		return &PRResult{Version: version}, nil
	}

	head, err := r.GH.BranchSHA(ctx, r.Cfg.Branch)
	if err != nil {
		return nil, err
	}
	sha, err := r.GH.CommitFiles(ctx, head, title, files)
	if err != nil {
		return nil, err
	}
	if err := r.GH.ForceBranch(ctx, r.releaseBranch(), sha); err != nil {
		return nil, err
	}

	open, err := r.GH.ListPulls(ctx, url.Values{
		"state": {"open"},
		"head":  {r.GH.Owner + ":" + r.releaseBranch()},
		"base":  {r.Cfg.Branch},
	})
	if err != nil {
		return nil, err
	}
	var pr github.PullRequest
	if len(open) > 0 {
		pr, err = r.GH.UpdatePull(ctx, open[0].Number, title, body)
		r.logf("updated release PR #%d: %s", pr.Number, title)
	} else {
		pr, err = r.GH.CreatePull(ctx, title, r.releaseBranch(), r.Cfg.Branch, body)
		r.logf("opened release PR #%d: %s", pr.Number, title)
	}
	if err != nil {
		return nil, err
	}
	if err := r.GH.AddLabels(ctx, pr.Number, LabelPending); err != nil {
		return nil, err
	}
	return &PRResult{Version: version, PR: pr}, nil
}

// GitHubRelease tags a release for every merged release PR still labelled
// pending.
func (r *Runner) GitHubRelease(ctx context.Context) ([]Created, error) {
	prs, err := r.mergedPendingPRs(ctx)
	if err != nil {
		return nil, err
	}
	if len(prs) == 0 {
		r.logf("no merged release PRs awaiting a release")
	}
	var created []Created
	for _, pr := range prs {
		version, ok := versionFromTitle(pr.Title)
		if !ok {
			r.logf("skipping PR #%d: cannot find version in title %q", pr.Number, pr.Title)
			continue
		}
		tag := r.Cfg.TagPrefix + version
		if r.Cfg.DryRun {
			r.logf("[dry run] would create release %s at %s from PR #%d", tag, pr.MergeCommitSHA, pr.Number)
			created = append(created, Created{Version: version, Tag: tag, PR: pr.Number})
			continue
		}

		existing, err := r.GH.ReleaseByTag(ctx, tag)
		if err != nil {
			return created, err
		}
		rel := existing
		if rel == nil {
			v, _ := semver.Parse(version)
			nr, err := r.GH.CreateRelease(ctx, tag, pr.MergeCommitSHA, tag, notesFromBody(pr.Body), v.Prerelease != "")
			if err != nil {
				return created, err
			}
			rel = &nr
			r.logf("created release %s: %s", tag, nr.HTMLURL)
		} else {
			r.logf("release %s already exists; relabelling PR #%d", tag, pr.Number)
		}
		if err := r.GH.RemoveLabel(ctx, pr.Number, LabelPending); err != nil {
			return created, err
		}
		if err := r.GH.AddLabels(ctx, pr.Number, LabelTagged); err != nil {
			return created, err
		}
		created = append(created, Created{Version: version, Tag: tag, URL: rel.HTMLURL, PR: pr.Number})
	}
	return created, nil
}

// NextVersion applies release-please's default versioning strategy.
func NextVersion(prev *semver.Version, cs []commits.Commit, cfg Config) (semver.Version, error) {
	for _, c := range cs {
		if c.ReleaseAs != "" {
			return semver.Parse(c.ReleaseAs)
		}
	}
	if prev == nil {
		initial := cfg.InitialVersion
		if initial == "" {
			initial = "1.0.0"
		}
		return semver.Parse(initial)
	}
	bump := semver.Patch
	for _, c := range cs {
		if c.Breaking {
			bump = semver.Major
			break
		}
		if c.Type == "feat" || c.Type == "feature" {
			bump = semver.Minor
		}
	}
	if prev.Major == 0 {
		if bump == semver.Major && cfg.BumpMinorPreMajor {
			bump = semver.Minor
		} else if bump == semver.Minor && cfg.BumpPatchForMinorPreMajor {
			bump = semver.Patch
		}
	}
	return prev.Bump(bump), nil
}

func (r *Runner) updatedFiles(ctx context.Context, version, notes string) (map[string]string, error) {
	files := map[string]string{}
	if p := r.Cfg.ChangelogPath; p != "" {
		existing, _, err := r.GH.GetFile(ctx, p, r.Cfg.Branch)
		if err != nil {
			return nil, err
		}
		files[p] = updater.PrependChangelog(existing, notes)
	}
	if p := r.Cfg.VersionFile; p != "" {
		files[p] = version + "\n"
	}
	if r.Cfg.ReleaseType == TypeGradle {
		updated := 0
		for _, p := range gradleFiles {
			content, found, err := r.GH.GetFile(ctx, p, r.Cfg.Branch)
			if err != nil {
				return nil, err
			}
			if !found {
				continue
			}
			next := updater.Generic(content, version)
			if p == "gradle.properties" {
				next = updater.GradleProperties(next, version)
			} else {
				next = updater.GradleBuild(next, version)
			}
			if next != content {
				files[p] = next
				updated++
			}
		}
		if updated == 0 {
			r.logf("warning: no version found in %s; only the changelog will change", strings.Join(gradleFiles, ", "))
		}
	}
	for _, p := range r.Cfg.ExtraFiles {
		content, found, err := r.GH.GetFile(ctx, p, r.Cfg.Branch)
		if err != nil {
			return nil, err
		}
		if !found {
			r.logf("warning: extra file %s not found; skipping", p)
			continue
		}
		if updated := updater.Generic(content, version); updated != content {
			files[p] = updated
		}
	}
	return files, nil
}

// DetectReleaseType guesses the release type from files on the branch.
func (r *Runner) DetectReleaseType(ctx context.Context) (string, error) {
	candidates := []struct{ file, typ string }{
		{"go.mod", TypeGo},
		{"build.gradle.kts", TypeGradle},
		{"build.gradle", TypeGradle},
		{"settings.gradle.kts", TypeGradle},
		{"settings.gradle", TypeGradle},
		{"gradle.properties", TypeGradle},
	}
	for _, c := range candidates {
		_, found, err := r.GH.GetFile(ctx, c.file, r.Cfg.Branch)
		if err != nil {
			return "", err
		}
		if found {
			return c.typ, nil
		}
	}
	return TypeSimple, nil
}

var moduleRe = regexp.MustCompile(`(?m)^module[ \t]+"?([^\s"]+)"?`)

// goModuleWarning flags a v2+ release of a Go module whose path lacks the
// /vN suffix, since `go get` will not resolve such tags.
func (r *Runner) goModuleWarning(ctx context.Context, next semver.Version) (string, error) {
	if r.Cfg.ReleaseType != TypeGo || next.Major < 2 {
		return "", nil
	}
	gomod, found, err := r.GH.GetFile(ctx, "go.mod", r.Cfg.Branch)
	if err != nil || !found {
		return "", err
	}
	m := moduleRe.FindStringSubmatch(gomod)
	suffix := fmt.Sprintf("/v%d", next.Major)
	if m == nil || strings.HasSuffix(m[1], suffix) {
		return "", nil
	}
	return fmt.Sprintf("this is a v%d release but go.mod declares `module %s`. Go modules at v2+ need the major version in the module path (`%s%s`), otherwise `go get` will not resolve the new tag. See https://go.dev/doc/modules/major-version.", next.Major, m[1], m[1], suffix), nil
}

func (r *Runner) latestRelease(ctx context.Context) (*semver.Version, string, error) {
	rels, err := r.GH.ListReleases(ctx, 5)
	if err != nil {
		return nil, "", err
	}
	var best *semver.Version
	var bestTag string
	for _, rel := range rels {
		if rel.Draft || !strings.HasPrefix(rel.TagName, r.Cfg.TagPrefix) {
			continue
		}
		v, err := semver.Parse(strings.TrimPrefix(rel.TagName, r.Cfg.TagPrefix))
		if err != nil {
			continue
		}
		if best == nil || v.Compare(*best) > 0 {
			best, bestTag = &v, rel.TagName
		}
	}
	return best, bestTag, nil
}

func (r *Runner) mergedPendingPRs(ctx context.Context) ([]github.PullRequest, error) {
	prs, err := r.GH.ListPulls(ctx, url.Values{
		"state":     {"closed"},
		"base":      {r.Cfg.Branch},
		"sort":      {"updated"},
		"direction": {"desc"},
	})
	if err != nil {
		return nil, err
	}
	var out []github.PullRequest
	for _, pr := range prs {
		if pr.MergedAt != nil && pr.HasLabel(LabelPending) {
			out = append(out, pr)
		}
	}
	return out, nil
}

var titleVersionRe = regexp.MustCompile(`release v?(\d+\.\d+\.\d+\S*)\s*$`)

func versionFromTitle(title string) (string, bool) {
	m := titleVersionRe.FindStringSubmatch(title)
	if m == nil {
		return "", false
	}
	if _, err := semver.Parse(m[1]); err != nil {
		return "", false
	}
	return m[1], true
}

// notesFromBody extracts the changelog section from a release PR body,
// dropping the "## version" heading since the release already has a title.
func notesFromBody(body string) string {
	body = strings.ReplaceAll(body, "\r\n", "\n")
	if i := strings.Index(body, "\n---\n"); i >= 0 {
		body = body[i+len("\n---\n"):]
	}
	if i := strings.LastIndex(body, "\n---\n"); i >= 0 {
		body = body[:i]
	}
	body = strings.TrimSpace(body)
	if strings.HasPrefix(body, "## ") {
		if i := strings.Index(body, "\n"); i >= 0 {
			body = body[i+1:]
		} else {
			body = ""
		}
	}
	return strings.TrimSpace(body)
}

func (r *Runner) sections() []changelog.Section {
	if r.Cfg.Sections != nil {
		return r.Cfg.Sections
	}
	return changelog.DefaultSections
}

func (r *Runner) repoURL() string {
	web := r.Cfg.WebURL
	if web == "" {
		web = "https://github.com"
	}
	return strings.TrimRight(web, "/") + "/" + r.GH.Owner + "/" + r.GH.Repo
}

func (r *Runner) now() time.Time {
	if r.Now != nil {
		return r.Now()
	}
	return time.Now()
}

func orNone(s string) string {
	if s == "" {
		return "the beginning of history"
	}
	return s
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
